export interface MoonPosition {
  /** Geocentric ecliptic longitude, radians (0..2pi). */
  longitude: number;
  /** Geocentric ecliptic latitude, radians. */
  latitude: number;
  /** Distance from Earth's center, km. */
  distanceKm: number;
}

/** Moon's geocentric position from Julian centuries T (TT/dynamical time). */
export function moonPosition(T: number): MoonPosition {
  const Lp = deg2rad(
    pMod(
      horner(T, [218.3164477, 481267.88123421, -0.0015786, 1 / 538841, -1 / 65194000]),
      360
    )
  );
  const D = deg2rad(
    pMod(
      horner(T, [297.8501921, 445267.1114034, -0.0018819, 1 / 545868, -1 / 113065000]),
      360
    )
  );
  const M = deg2rad(pMod(horner(T, [357.5291092, 35999.0502909, -0.0001536, 1 / 24490000]), 360));
  const Mp = deg2rad(
    pMod(horner(T, [134.9633964, 477198.8675055, 0.0087414, 1 / 69699, -1 / 14712000]), 360)
  );
  const F = deg2rad(
    pMod(horner(T, [93.272095, 483202.0175233, -0.0036539, -1 / 3526000, 1 / 863310000]), 360)
  );

  const A1 = deg2rad(119.75 + 131.849 * T);
  const A2 = deg2rad(53.09 + 479264.29 * T);
  const A3 = deg2rad(313.45 + 481266.484 * T);

  const E = horner(T, [1, -0.002516, -0.0000074]);
  const E2 = E * E;

  let sumL =
    3958 * Math.sin(A1) + 1962 * Math.sin(Lp - F) + 318 * Math.sin(A2);
  let sumR = 0;
  let sumB =
    -2235 * Math.sin(Lp) +
    382 * Math.sin(A3) +
    175 * Math.sin(A1 - F) +
    175 * Math.sin(A1 + F) +
    127 * Math.sin(Lp - Mp) -
    115 * Math.sin(Lp + Mp);

  for (const row of TA) {
    const [d, m, mp, f, coefL, coefR] = row;
    const arg = d * D + m * M + mp * Mp + f * F;
    const sinArg = Math.sin(arg);
    const cosArg = Math.cos(arg);
    const eFactor = Math.abs(m) === 1 ? E : Math.abs(m) === 2 ? E2 : 1;
    sumL += coefL * sinArg * eFactor;
    sumR += coefR * cosArg * eFactor;
  }

  for (const row of TB) {
    const [d, m, mp, f, coefB] = row;
    const arg = d * D + m * M + mp * Mp + f * F;
    const sinArg = Math.sin(arg);
    const eFactor = Math.abs(m) === 1 ? E : Math.abs(m) === 2 ? E2 : 1;
    sumB += coefB * sinArg * eFactor;
  }

  return {
    longitude: pMod(Lp + deg2rad(sumL * 1e-6), 2 * Math.PI),
    latitude: deg2rad(sumB * 1e-6),
    distanceKm: 385000.56 + sumR * 1e-3,
  };
}
